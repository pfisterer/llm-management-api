// listServers godoc
//
//	@ID			listGPUServers
//	@Summary	My JupyterHub servers
//	@Tags		gpu
//	@Produce	json
//	@Security	BearerAuth
//	@Param			limit	query		int		false	"page size; default 100, at most 500"
//	@Param			offset	query		int		false	"how many entries to skip"
//	@Success	200	{object}	Page{items=[]gpu.Server}
//	@Failure	400	{object}	ErrorResponse
//	@Failure	502	{object}	ErrorResponse
//	@Router		/v1/gpu/servers [get]
func (s *Server) listServers(c *gin.Context) {
	r, ok := pageRequest(c)
	if !ok {
		return
	}
	servers, err := s.gpu.Servers(c.Request.Context(), caller(c).Email)
	if err != nil {
		s.fail(c, gpuErrors, "list servers", err)
		return
	}
	c.JSON(http.StatusOK, page.Of(servers, r))
}

// stopServer godoc
//
//	@ID			stopGPUServer
//	@Summary	Stop one of my servers
//	@Description	Named servers are removed after stopping; the home stays. The default server has no name and is addressed as "-".
//	@Tags		gpu
//	@Security	BearerAuth
//	@Param		name	path	string	true	"Server name, \"-\" for the default server"
//	@Success	204
//	@Failure	404	{object}	ErrorResponse
//	@Router		/v1/gpu/servers/{name} [delete]
func (s *Server) stopServer(c *gin.Context) {
	name := strings.TrimSpace(c.Param("name"))
	// The default server's name is empty, which a path cannot carry: "-" stands for it.
	if name == "-" {
		name = ""
	}
	if err := s.gpu.StopServer(c.Request.Context(), caller(c).Email, name); err != nil {
		s.fail(c, gpuErrors, "stop server", err)
		return
	}
	c.Status(http.StatusNoContent)
}

// serverNameRE are the names of servers: generated by the start (<project>-<profile>[-n]) or "-" for the default server.
var serverNameRE = regexp.MustCompile(`^(-|[A-Za-z0-9][A-Za-z0-9._-]{0,254})$`)

// getServerProgress godoc
//
//	@ID			getGPUServerProgress
//	@Summary	How far the start of one of my servers got
//	@Description	JupyterHub's event log of the start (waiting for a GPU, pulling the image, …), and whether it ended ready or failed with the hub's reason. starting is false when the server is not starting and nothing failed. Ask again every few seconds while it starts.
//	@Tags		gpu
//	@Produce	json
//	@Security	BearerAuth
//	@Param		name	path		string	true	"Server name, \"-\" for the default server"
//	@Success	200		{object}	gpu.Progress
//	@Failure	400		{object}	ErrorResponse
//	@Failure	404		{object}	ErrorResponse
//	@Router		/v1/gpu/servers/{name}/progress [get]
func (s *Server) getServerProgress(c *gin.Context) {
	name := strings.TrimSpace(c.Param("name"))
	if !serverNameRE.MatchString(name) {
		abort(c, http.StatusBadRequest, "invalid", "Ungültiger Workspace-Name.")
		return
	}
	if name == "-" {
		name = ""
	}
	p, err := s.gpu.ServerProgress(c.Request.Context(), caller(c).Email, name)
	if err != nil {
		s.fail(c, gpuErrors, "server progress", err)
		return
	}
	c.JSON(http.StatusOK, p)
}

// StartOptionsResponse is what a start may choose: the caller's projects (with their profiles, GPU classes, environment, storage and end) and the profiles.
type StartOptionsResponse struct {
	Projects []HubProject        `json:"projects"`
	Profiles []workspace.Profile `json:"profiles"`
	// LLMProjects are the caller's projects with LLM tokens, for the choice whose tokens the server's LLM key draws from; besides them a start may always choose llm_project "none" (without LLM). What a start without a choice gets is each project's llm_default.
	LLMProjects []HubLLMProject `json:"llm_projects"`
}

// getStartOptions godoc
//
//	@ID			getGPUStartOptions
//	@Summary	What I can start
//	@Description	The caller's active projects as a start sees them, and the profiles. Admins without a project get no projects: every start needs one.
//	@Tags		gpu
//	@Produce	json
//	@Security	BearerAuth
//	@Success	200	{object}	StartOptionsResponse
//	@Router		/v1/gpu/start-options [get]
func (s *Server) getStartOptions(c *gin.Context) {
	c.JSON(http.StatusOK, s.startOptionsOf(c.Request.Context(), s.myProjects(c), caller(c).Tokens))
}

// startOptionsOf is what a start may choose, for the REST route and the MCP tool alike: mine are the caller's active projects, tokens theirs for the LLM pools.
func (s *Server) startOptionsOf(ctx context.Context, mine []workspace.Mine, tokens []string) StartOptionsResponse {
	llm := llmProjects(ctx, s.quota, tokens)
	projects := hubProjects(ctx, s.ws, mine)
	for i, m := range mine {
		// What a start without a choice gets (the same rule as the hub's workspace key): the start page preselects it.
		pick, _ := llmProjectFor(llm, "", m.Slug, m.DefaultLLMProject)
		p := &projects[i]
		p.DefaultLLMProject, p.LLMDefault, p.LLMDefaultSource, p.LLMDefaultUnavailable = m.DefaultLLMProject, pick.Project, pick.Source, pick.Unavailable
		if p.LLMDefault == "" {
			p.LLMDefault = gpu.NoLLM
		}
	}
	return StartOptionsResponse{Projects: projects, Profiles: s.ws.Catalog(ctx).Profiles, LLMProjects: llm}
}

// StartServerRequest chooses a project, a profile and, for a profile with a GPU, a GPU class (optional when the project has only one).
type StartServerRequest struct {
	Project  string `json:"project" binding:"required"`
	Profile  string `json:"profile" binding:"required"`
	GPUClass string `json:"gpu_class"`
	// LLMProject is whose LLM tokens the server's key draws from: the slug of one of llm_projects of the start options, "none" for a server without LLM key, or empty = the project's llm_default of the start options.
	LLMProject string `json:"llm_project" example:"none"`
}

// startServer godoc
//
//	@ID			startGPUServer
//	@Summary	Start a server
//	@Description	Starts a new named server in JupyterHub with the project's environment. The hub checks the start as for every start (membership, profile, GPU class, limits per person, GPU quota); a refusal is 409 with its reason. 202 with the server while it starts.
//	@Tags		gpu
//	@Accept		json
//	@Produce	json
//	@Security	BearerAuth
//	@Param		start	body		StartServerRequest	true	"what to start"
//	@Success	202		{object}	gpu.Server
//	@Failure	400		{object}	ErrorResponse
//	@Failure	409		{object}	ErrorResponse
//	@Router		/v1/gpu/servers [post]
func (s *Server) startServer(c *gin.Context) {
	var req StartServerRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		abort(c, http.StatusBadRequest, "invalid", "project und profile fehlen.")
		return
	}
	o, msg := s.startOptions(c, req)
	if msg != "" {
		abort(c, http.StatusBadRequest, "invalid", msg)
		return
	}
	srv, err := s.gpu.StartServer(c.Request.Context(), caller(c).Email, o)
	if err != nil {
		s.fail(c, gpuErrors, "start server", err)
		return
	}
	c.JSON(http.StatusAccepted, srv)
}

// startOptions checks a start against the caller's projects, as the start page offers it; the hub checks the limits.
func (s *Server) startOptions(c *gin.Context, req StartServerRequest) (gpu.StartOptions, string) {
	return s.startOptionsFor(c.Request.Context(), s.myProjects(c), caller(c).Tokens, req)
}

// startOptionsFor is startOptions without gin, for the REST route and the MCP tool alike: mine are the caller's active projects, tokens theirs for the LLM pools; the message says what is wrong with the request, empty when nothing is.
func (s *Server) startOptionsFor(ctx context.Context, mine []workspace.Mine, tokens []string, req StartServerRequest) (gpu.StartOptions, string) {
	var project *workspace.Mine
	for _, m := range mine {
		if m.Slug == req.Project {
			project = &m
		}
	}
	if project == nil {
		return gpu.StartOptions{}, "Kein aktives Projekt " + req.Project + " mit Workspace-Zugang."
	}
	if !slices.Contains(project.Profiles, req.Profile) || (req.Profile == workspace.SplitProfile && !project.Derived()) {
		return gpu.StartOptions{}, "Diese Umgebung ist im Projekt nicht freigegeben."
	}
	o := gpu.StartOptions{Project: req.Project, Profile: req.Profile, LLMProject: req.LLMProject}
	if o.LLMProject != "" && o.LLMProject != gpu.NoLLM {
		if _, ok := llmProjectFor(llmProjects(ctx, s.quota, tokens), o.LLMProject, "", ""); !ok {
			return gpu.StartOptions{}, "Dieses LLM-Projekt steht nicht zur Wahl."
		}
	}
	usesGPU := false
	for _, p := range s.ws.Catalog(ctx).Profiles {
		if p.Slug == req.Profile {
			usesGPU = p.GPU
		}
	}
	if !usesGPU {
		return o, ""
	}
	o.GPUClass = req.GPUClass
	if o.GPUClass == "" && len(project.GPUClasses) == 1 {
		o.GPUClass = project.GPUClasses[0]
	}
	if !project.AllowsGPUClass(o.GPUClass) {
		return gpu.StartOptions{}, "Diese GPU-Klasse ist im Projekt nicht freigegeben."
	}
	return o, ""
}
